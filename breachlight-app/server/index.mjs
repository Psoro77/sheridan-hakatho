import { createServer } from 'node:http';
import { loadConfig } from './config.mjs';
import { makePool } from './database.mjs';
import { createHandler } from './app.mjs';
const config=loadConfig();
if(!['127.0.0.1','localhost'].includes(config.host)&&!config.apiKey)throw new Error('Set BREACHLIGHT_API_KEY before binding the API beyond localhost.');
const pool=makePool(config);
const server=createServer(createHandler(pool));
server.requestTimeout=240000;
server.listen(config.port,config.host,()=>console.log(`Breachlight API listening on http://${config.host}:${config.port} (credentials remain server-side)`));
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>{server.close();pool?.end().finally(()=>process.exit(0));setTimeout(()=>process.exit(0),2000).unref();});
